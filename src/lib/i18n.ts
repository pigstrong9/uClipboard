const dictionaries: Record<Language, Record<string, string>> = {
  'zh-CN': zh,
  'en-US': en,
};

export function resolveLanguage(setting: string | undefined): Language {
  if (setting === 'zh-CN' || setting === 'en-US') return setting;
  if (typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('zh')) {
    return 'zh-CN';
  }
  return 'en-US';
}

export function translate(
  language: Language,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const template = dictionaries[language][key] ?? dictionaries['zh-CN'][key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    vars[name] === undefined ? match : String(vars[name]),
  );
}

export type Translate = (key: string, vars?: Record<string, string | number>) => string;

export function createTranslate(language: Language): Translate {
  return (key, vars) => translate(language, key, vars);
}
