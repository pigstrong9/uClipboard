use std::path::Path;

use clipboard_rs::common::RustImage;
#[cfg(not(target_os = "windows"))]
use clipboard_rs::RustImageData;
use clipboard_rs::{Clipboard, ClipboardContent, ClipboardContext};

use crate::models::{ClipItem, ClipKind};

pub struct RawCapture {
    pub kind: ClipKind,
    pub text: Option<String>,
    pub html: Option<String>,
    pub image_png: Option<Vec<u8>>,
    pub files: Vec<String>,
}

pub trait ClipboardSource: Send + Sync {
    /// `Err` means the clipboard itself could not be inspected (so the caller should
    /// retry); `Ok(None)` means it was readable but held nothing recordable.
    fn read(&self) -> Result<Option<RawCapture>, String>;
    /// Checked before `read`, so private content is never decoded. `Err` means the format
    /// list was unavailable; the caller retries instead of assuming the clip is safe.
    fn privacy(&self) -> Result<bool, String> {
        Ok(false)
    }
    fn write_with_options(&self, item: &ClipItem, media_dir: &Path, plain_text: bool) -> bool;
    fn write_merged(&self, text: Option<&str>, files: &[String]) -> bool;
    fn write_image_png(&self, _png: &[u8]) -> bool {
        false
    }
}

fn existing_files(files: Vec<String>) -> Vec<String> {
    files
        .into_iter()
        .filter(|path| !path.is_empty() && Path::new(path).exists())
        .collect()
}

pub struct SystemClipboard;

impl ClipboardSource for SystemClipboard {
    fn read(&self) -> Result<Option<RawCapture>, String> {
        let ctx = ClipboardContext::new().map_err(|error| error.to_string())?;
        // Enumerating formats first separates "clipboard is inaccessible right now"
        // (retry) from "nothing we can record" (remember the revision and move on).
        let formats = ctx.available_formats().map_err(|error| error.to_string())?;
        if formats.is_empty() {
            return Ok(None);
        }

        if let Ok(files) = ctx.get_files() {
            if !files.is_empty() {
                return Ok(Some(RawCapture {
                    kind: ClipKind::Files,
                    text: None,
                    html: None,
                    image_png: None,
                    files,
                }));
            }
        }

        if let Ok(image) = ctx.get_image() {
            if !image.is_empty() {
                if let Ok(png) = image.to_png() {
                    return Ok(Some(RawCapture {
                        kind: ClipKind::Image,
                        text: None,
                        html: None,
                        image_png: Some(png.get_bytes().to_vec()),
                        files: Vec::new(),
                    }));
                }
            }
        }

        if let Ok(text) = ctx.get_text() {
            if !text.trim().is_empty() {
                // Some clipboard bridges write UTF-8 bytes into CF_UNICODETEXT,
                // which clipboard-rs decodes as UTF-16LE into CJK-looking noise.
                // Recover the original payload before it reaches history/hash.
                let text = crate::clipboard::text::repair_mojibake(&text).unwrap_or(text);
                let html = ctx.get_html().ok().filter(|h| !h.trim().is_empty());
                return Ok(Some(RawCapture {
                    kind: ClipKind::Text,
                    text: Some(text),
                    html,
                    image_png: None,
                    files: Vec::new(),
                }));
            }
        }

        Ok(None)
    }

    fn privacy(&self) -> Result<bool, String> {
        let ctx = ClipboardContext::new().map_err(|error| error.to_string())?;
        let formats = ctx.available_formats().map_err(|error| error.to_string())?;
        for format in formats {
            let name = format.to_ascii_lowercase();
            if name.contains("excludeclipboardcontentfrommonitorprocessing")
                || name.contains("clipboard viewer ignore")
                || name.contains("org.nspasteboard.concealedtype")
                || name.contains("org.nspasteboard.transienttype")
                || name.contains("org.nspasteboard.autogeneratedtype")
            {
                return Ok(true);
            }
            if name.contains("canincludeinclipboardhistory") {
                match crate::platform::clipboard_format_dword(&format) {
                    Some(0) => return Ok(true),
                    Some(_) => {}
                    None => {
                        if let Ok(buffer) = ctx.get_buffer(&format) {
                            let is_zero = buffer.len() >= 4
                                && u32::from_le_bytes([buffer[0], buffer[1], buffer[2], buffer[3]])
                                    == 0;
                            let is_zero_text = std::str::from_utf8(&buffer)
                                .map(|text| text.trim_matches('\0').trim() == "0")
                                .unwrap_or(false);
                            if is_zero || is_zero_text {
                                return Ok(true);
                            }
                        }
                    }
                }
            }
        }
        Ok(false)
    }

    fn write_with_options(&self, item: &ClipItem, media_dir: &Path, plain_text: bool) -> bool {
        let Ok(ctx) = ClipboardContext::new() else {
            return false;
        };
        match item.kind {
            ClipKind::Text => {
                if !plain_text {
                    let html = item
                        .extra
                        .as_deref()
                        .and_then(|raw| serde_json::from_str::<serde_json::Value>(raw).ok())
                        .and_then(|value| {
                            value
                                .get("html")
                                .and_then(|html| html.as_str())
                                .map(|html| html.to_string())
                        })
                        .filter(|html| !html.trim().is_empty());
                    if let Some(html) = html {
                        return ctx
                            .set(vec![
                                ClipboardContent::Text(item.content.clone()),
                                ClipboardContent::Html(html),
                            ])
                            .is_ok();
                    }
                }
                ctx.set_text(item.content.clone()).is_ok()
            }
            ClipKind::Files => {
                let Ok(files) = serde_json::from_str::<Vec<String>>(&item.content) else {
                    return false;
                };
                // History can outlive the files; writing missing paths would produce a
                // paste that silently does nothing, so only existing ones are offered.
                let files = existing_files(files);
                if files.is_empty() {
                    return false;
                }
                ctx.set_files(files).is_ok()
            }
            ClipKind::Image => {
                let path = media_dir.join(&item.content);
                let Ok(bytes) = std::fs::read(path) else {
                    return false;
                };
                #[cfg(target_os = "windows")]
                {
                    crate::platform::set_clipboard_image_png(&bytes)
                }
                #[cfg(not(target_os = "windows"))]
                {
                    let Ok(image) = RustImageData::from_bytes(&bytes) else {
                        return false;
                    };
                    ctx.set_image(image).is_ok()
                }
            }
        }
    }

    fn write_merged(&self, text: Option<&str>, files: &[String]) -> bool {
        let Ok(ctx) = ClipboardContext::new() else {
            return false;
        };
        let mut contents = Vec::new();
        if let Some(text) = text {
            if !text.is_empty() {
                contents.push(ClipboardContent::Text(text.to_string()));
            }
        }
        let files = existing_files(files.to_vec());
        if !files.is_empty() {
            contents.push(ClipboardContent::Files(files));
        }
        if contents.is_empty() {
            return false;
        }
        ctx.set(contents).is_ok()
    }

    fn write_image_png(&self, png: &[u8]) -> bool {
        #[cfg(target_os = "windows")]
        {
            crate::platform::set_clipboard_image_png(png)
        }
        #[cfg(not(target_os = "windows"))]
        {
            let Ok(ctx) = ClipboardContext::new() else {
                return false;
            };
            let Ok(image) = RustImageData::from_bytes(png) else {
                return false;
            };
            ctx.set_image(image).is_ok()
        }
    }
}
